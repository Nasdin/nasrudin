interface ProseOpts {
  /** Lean qualifier from origin_payload.Imported.source, if any. */
  importedFrom?: string | null;
  /** Domain enum string if available. */
  domain?: string | null;
}

export function statementToProse(canonical: string, opts: ProseOpts = {}): string | null {
  const imp = opts.importedFrom;
  if (imp) {
    const hit = CURATED[imp];
    if (hit) return hit;
  }

  // Templated fallback: derive a humanised title and emit a stilted but
  // informative gloss. We don't try to summarise the body of the statement
  // structurally — that path leads to confidently-wrong summaries. Instead
  // we tell the reader what the theorem is _named_ for, and let the
  // rendered LaTeX below carry the actual content.
  const title = leanToHumanTitle(imp ?? null);
  if (title) {
    const domain = opts.domain ?? null;
    if (domain) {
      return `Concerns ${title.toLowerCase()} — a result in ${domainLabel(domain)}. See the formal statement below for the precise quantifiers and conclusion.`;
    }
    return `Concerns ${title.toLowerCase()}. See the formal statement below for the precise quantifiers and conclusion.`;
  }

  // No qualifier and not curated — we have nothing trustworthy to say.
  // Returning null lets the page suppress the prose box entirely rather
  // than emit something hand-wavy.
  if (!canonical || !canonical.trim()) return null;
  return null;
}

function domainLabel(raw: string): string {
  // Avoid a circular import by inlining the few labels we use here. The
  // canonical mapping is in lib/domains.ts.
  switch (raw) {
    case 'PureMath':
      return 'pure mathematics';
    case 'ClassicalMechanics':
      return 'classical mechanics';
    case 'Electromagnetism':
      return 'electromagnetism';
    case 'SpecialRelativity':
      return 'special relativity';
    case 'GeneralRelativity':
      return 'general relativity';
    case 'QuantumMechanics':
      return 'quantum mechanics';
    case 'QuantumFieldTheory':
      return 'quantum field theory';
    case 'Thermodynamics':
      return 'thermodynamics';
    case 'StatisticalMechanics':
      return 'statistical mechanics';
    default:
      return raw.toLowerCase();
  }
}
