//
// The fallback intentionally produces a slightly-stilted line like
//
//   "For every n : ℕ and every v : Lorentz vector, …"
//
// rather than trying to be fluent — it's better to be obviously
// templated than to fake an authoritative-sounding summary that's
// subtly wrong.

